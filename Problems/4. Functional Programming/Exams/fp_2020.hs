recommender pl = \r@(a,_,d) ->
  let avgDuration artist = sum (map (\(_,_,dur) -> dur) (filter (\(a1,_,_) -> a1 == artist) pl)) `div`
                           length (filter (\(a1,_,_) -> a1 == artist) pl)

    option1 = filter (\(a1,_,d1) -> a1 == a && d1 > d) pl

    option2 = if avgDuration a < avgDurationAll then filter (\(a1,_,_) -> avgDuration a1 < avgDuration a) pl
              else dropWhile (/= r) (tail pl)

    avgDurationAll = sum (map (\(_,_,d) -> d) pl) `div` length pl

    in if not (null option1) then head option1
       else if not (null option2) then last option2
       else head pl

