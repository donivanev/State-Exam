-- Музикално произведение се описва с наредена тройка от име на автор, заглавие на произведението и дължина в секунди.
-- Даден е непразен списък от музикални произведения pl, в който те са подредени в нарастващ ред по дължина. Препоръчваща
-- функция наричаме функция, която приема наредена тройка, описваща текущо възпроизвеждащо се музикално произведение и връща
-- заглавие на произведение, което се препоръчва да бъде следващото възпроизведено. Компанията 𝜆ify е патентовала алгоритъм за
-- препоръчваща функция, която за текущо възпроизвеждащо се произведение p с първи компонент (автор) a работи по следния начин
-- за списък pl:
--      1. Препоръчва следващото по дължина произведение на a в pl, ако има такова.
--      2. В противен случай, препоръчва произведение с максимална дължина в pl из произведенията на всички автори, за които
--      средната дължина на произведенията в pl е по-малка от средната дължина на произведенията на a в pl, ако има такива.
--      3. В противен случай, препоръчва следващото по дължина произведение в pl след p, а ако такова няма, препоръчва отново p.
-- Да се попълнят празните полета по-долу така, че функцията recommender pl да връща препоръчваща функция, реализираща алгоритъма
-- на 𝜆ify, описан по-горе, върху списък pl. Функцията avgDuration да връща средната дължина на произведенията на author в pl.
