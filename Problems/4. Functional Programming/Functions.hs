-- Функции

mystery :: Int -> Int -> Int
mystery x y
 | x == 0 = y
 | otherwise = x

mystery 0 y = y
mystery x _ = x -- y не се използва, затова може да се замени с _

-- двете функции правят едно и също, но втората изполва pattern matching

