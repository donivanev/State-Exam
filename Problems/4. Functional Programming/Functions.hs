-- Образци на списъци

-- Всеки списък е или празен ([]) или има глава и опашка и може да се запише като x:xs, където x е първият елемент, а xs е опашката
-- Операторът : е конструктор на списъци, тъй като всеки списък може да бъде конструиран по единствен начин с използване на [] и :

-- Конструкцията case

firstDigit :: String -> Char
firstDigit str = case (digits str) of
    [] -> '\0'
    (x:_) -> x

-- Примитивна рекурсия върху списъци

sum :: [Int] -> Int
sum [] = 0 -- базов случай
sum (x:xs) = x + sum xs -- общ случай

concat :: [[a]] -> [a]
concat [] = []
concat (x:xs) = x ++ concat xs

elem :: Int -> [Int] -> Bool
elem x [] = False
elem x (y:ys) = (x == y) || (elem x ys)

selectEven :: [Int] -> [Int]
selectEven [] = []
selectEven (x:xs)
 | isEven x = x : selectEven xs
 | otherwise = selectEven xs

-- Обща рекурсия върху списъци

quickSort :: [Int] -> [Int]
quickSort [] = []
quickSort (x:xs) = quickSort [y | y <- xs, y <= x] ++ [x] ++ quickSort [ y | y <- xs, y > x]