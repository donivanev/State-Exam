USE ships;

-- Посочете заявката, която извежда всички държави, които имат както класове с по-малко от 9 оръдия (numguns), така и класове с
-- над 12 оръдия:

SELECT DISTINCT COUNTRY FROM CLASSES WHERE NUMGUNS < 9 AND NUMGUNS > 12;

SELECT DISTINCT C1.COUNTRY FROM CLASSES C1 JOIN CLASSES C2 ON C1.COUNTRY = C2.COUNTRY WHERE C1.NUMGUNS < 9 AND C2.NUMGUNS > 12; -- ✓

SELECT COUNTRY FROM CLASSES WHERE NUMGUNS < 9
UNION
SELECT COUNTRY FROM CLASSES WHERE NUMGUNS > 12;

SELECT DISTINCT COUNTRY FROM CLASSES WHERE NUMGUNS < 9 AND COUNTRY = (SELECT COUNTRY FROM CLASSES WHERE NUMGUNS > 12)

-- Посочете заявката, която за всяка държава, участвала в не повече от 4 битки, извежда името й и броя битки, в които е участвала.
-- Ако дадена държава няма нито един кораб или не е участвала в нито една битка, за нея да извежда 0.

SELECT COUNTRY, COUNT(DISTINCT BATTLE) FROM CLASSES C, SHIPS S, OUTCOMES O WHERE C.CLASS=S.CLASS AND S.NAME=O.SHIP
GROUP BY COUNTRY HAVING COUNT(DISTINCT O.BATTLE) < 4;

SELECT COUNTRY, COUNT(O.BATTLE) AS NUM_BATTLES FROM CLASSES C LEFT JOIN SHIPS S ON C.CLASS=S.CLASS
LEFT JOIN OUTCOMES O ON S.NAME=O.SHIP GROUP BY COUNTRY HAVING COUNT(O.BATTLE) < 4; -- ✓

SELECT COUNTRY, COUNT(DISTINCT BATTLE) FROM OUTCOMES JOIN SHIPS ON NAME=SHIP RIGHT JOIN CLASSES ON CLASSES.CLASS=SHIPS.CLASS
GROUP BY COUNTRY HAVING COUNT(DISTINCT OUTCOMES.BATTLE) <= 3;

SELECT C.COUNTRY, COUNT(O.BATTLE) FROM CLASSES AS C INNER JOIN SHIPS AS S ON C.CLASS=S.CLASS
LEFT OUTER JOIN OUTCOMES AS O ON S.NAME=O.SHIP WHERE COUNT(O.BATTLE) <= 3

