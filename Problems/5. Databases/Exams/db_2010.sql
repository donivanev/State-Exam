USE movies;

-- Да се посочи заявката, извеждаща всички актриси, които не са играли в нито един филм с име, започващо с буквата А.
-- Актриси, за които в базата от данни няма информация за техните участия, също трябва да бъдат изведени.

SELECT DISTINCT NAME FROM MOVIESTAR LEFT JOIN STARSIN ON NAME = STARNAME WHERE GENDER = 'F' AND MOVIETITLE NOT LIKE 'A%';

SELECT NAME FROM MOVIESTAR JOIN STARSIN ON STARNAME = NAME WHERE GENDER = 'F' AND MOVIETITLE LIKE 'A%' GROUP BY NAME
HAVING COUNT(*) = 0;

SELECT MS.NAME FROM MOVIESTAR MS WHERE MS.GENDER = 'F' AND NOT EXISTS
(SELECT 1 FROM STARSIN SI WHERE SI.STARNAME = MS.NAME AND SI.MOVIETITLE LIKE 'A%'); -- ✓

SELECT NAME FROM MOVIESTAR WHERE GENDER = 'F' AND NAME IN (SELECT DISTINCT STARNAME FROM STARSIN WHERE NOT MOVIETITLE LIKE 'A%');

-- Да се посочи заявката, която за всяка филмова звезда (без значение от пола), родена преди 1990 г., извежда възрастта, на която
-- е играла за първи път във филм. Звезди, за които няма информация за техните участия във филми, не трябва да бъдат извеждани.

SELECT NAME, MIN( MOVIEYEAR - YEAR(BIRTHDATE) ) AS DEBUT_AGE FROM MOVIESTAR JOIN STARSIN ON NAME = STARNAME
WHERE YEAR(BIRTHDATE) < 1990 GROUP BY NAME;

SELECT NAME, MIN(MOVIEYEAR) - YEAR(BIRTHDATE) AS DEBUT_AGE FROM MOVIESTAR JOIN STARSIN ON NAME = STARNAME
WHERE YEAR(BIRTHDATE) < 1990 GROUP BY NAME;

SELECT NAME, MIN(MOVIEYEAR) - YEAR(BIRTHDATE) AS DEBUT_AGE FROM MOVIESTAR
LEFT JOIN STARSIN ON NAME = STARNAME AND YEAR(BIRTHDATE) < 1990 GROUP BY NAME HAVING MIN(MOVIEYEAR);

SELECT DISTINCT MS.NAME, MOVIEYEAR - YEAR(BIRTHDATE) AS DEBUT_AGE FROM MOVIESTAR MS, STARSIN
WHERE MS.NAME = STARNAME AND YEAR(BIRTHDATE) < 1990 HAVING MOVIEYEAR <= ALL
(SELECT MOVIEYEAR FROM STARSIN SI WHERE SI.STARNAME = MS.NAME);