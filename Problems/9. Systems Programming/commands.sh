# Работа с файлове и директории

cat [f1 f2 ... fN ] # показва съдържанието на файл/овете
touch f1 [ f2 ... fN ] # създава празни файлове
tee [f1 f2 ... fN ] # създава файловете f1 f2 и ни позволява да пишем в тях едновременно
cp [source] [destination] # копира файлове
cp f1 f2 f3 path_to_dir # примерно използване
cp f1 f2 # копираме съдържанието на f1 във f2
mv f1 dir1 # премества файла f1 в указаната директория
mv f1 f2 # преименува файла f1 на f2
mkdir f1 [ f2 ... fN ] # създава празни директории
rmdir f1 [ f2 ... fN ] # трие само празни директории
rm f1 [ f2 ... fN ] # трие файлове
rm -i f1 [ f2 ... fN ] # пуска ни запитване дали искаме да изтрием файловете
rm -r  dir # рекурсивно триене, чрез него можем да изтрием непразна директория

# Работа със съдържание на файлове

file f1 # дава информация за типа на файла
wc [-lcw] [ f1 f2 ... fN ] # брои: -l - редове; -c - символи; -w - думи
# Ако не зададем опция командата изписва: бр. редове, бр. символи, бр. думи и името на файла
head [-cl]  f1 [ f2 ... fN ] # командата без аргументи по подразбиране дава първите 10 реда от указаните файлове
# Опции : -n - дава първите num реда от файловете; -c - дава първите num байта от файла
tail [-cl] f1 [ f2 ... fN ] # без аргументи дава последните 10 реда от указаните файлове
# Опции: -l - дава последните n реда от файловете; -c - дава последните n байта от файла
more f1 # ако имаме голям файл го показва екран по екран
less f1 # подобно на more, но докато more показва файла само отгоре-надолу, less позволява да се движим и в двете посоки.
sort f1 # сортира f1 по редове
# Опции: -o output_file - вместо резултата да се покаже на екрана се записва в output_file

comm f1 f2 # сравнява два сортирани файла ред по ред. Изходът е 3 колони - 1-ва колона е уникалните редове за f1, 2-ра е уникалните редове за f2, а третата е редове, които са еднакви в двата файла
diff f1 f2 # сравнява два файла ред по ред. Дава ни кои редове и по какъв начин трябва да бъдат променени в единия файл, за да бъдат двата файла идентични.
cmp f1 f2 # сравнява 2 файла байт по байт и ако файловете са еднакви то командата не връща нищо; ако файловете се различават, командата връща първата позиция, на която се различават
-s # не извежда нищо на стандартния изход; генерира код на завършване на командата true или false

cut [options] [files] - реже части от всеки ред на файл
# Опции: -c - извлича специфично указани символи
# Примери:
cut -c 1-3,8-10 f1 # показва първите 3 символа от всеки ред на файла, прескача до 8-мия и показва от 8-мия до 10-тия
cut -c 1,5,7 f1 # показва 1-вия, 5-тия и 7-мия символ от всеки ред на файла f1
    -f # реже по номер на колона. Ако не е указан разделител реже по whitespace
    -d # указва по какъв разделител да се реже
# -f и -d често се ползват заедно
cut -d ":" -f 1-3 f1 # показва първите 3 колони от файла f1

tr [options] [SET1] [SET2] # не работи с файлове, а със стандартния вход.
# Заменя или изтрива специфични символи в подаден низ, където SET1 е множеството от символи, които трябва да се заменят, SET2 е множеството, с което да заменим символите от SET1 в низа. Ако първото множество е по-голямо – последния символ се използва многократно.
# Ако второто е по-голямо – последните символи се игнорират
-d # изтрива всички срещания на символите от SET1
-s # замества повтарящите се символи, изброени в SET1, само с един символ

grep str file # търси низ/регулярен израз във файл. Като резултат командата връща редовете от файла, в които се съдържа низа/регулярния израз. Изразите:
   grep –n str file # показва номера на реда във файла
   grep -h str f1 f2 f3 # не показва името на файла
grep -v str file # връща редовете, в които не се съдържа низа/рег. Израз
grep -q str file # не извежда нищо на стандартния изход; генерира код на завършване на командата true или false

find # командата без аргументи извежда на екрана абсолютно всички файлове (дори и тези в поддиректориите) на текущата директория, в която се намираме
    # Синтаксис: find [dir-to-be-searched] [arguments]
    # Аргументи:
-name # търси по име на файл
-type # търси по тип на файл
-user # търси по притежател на файла
-group # търси по групата, притежател на файла
-size # търси по размер на файла (трябва да специфицирате мерната единица)
-exec # изпълнява команда върху всеки един намерен резултат


