# Има 2 начина за смяна правата на достъп:

# 1. Задаване чрез число в 8-мична бройна система: 000-777.
# Пример:
chmod 0755 f1

# Как можем да изчислим всяка цифра?
# Знаем, че правата за достъп на файловете изглеждат така:
drwxr-xr-x 2 user user 4096 окт 5 2018 directory
-rw-r--r-- 1 user user 2243935 дек 8 2017 file
# Като на първата позиция стои съответно индикатор дали това е директория (d) или файл (-). Следват 3 групи от 3 символа read, write, execute, които указват правата за достъп съответно на текущия потребител, групата му и всички останали. Ако някое право е забранено съответно на мястото му присъства -.
# За да получим 3-цифрения код за правата за достъп просто заместваме r,w,x с 1-ца, а - с 0.
Пример:
-rw-r--r-- # е файл, който може да се чете и пише от текущия потребител и само да се чете от групата и всички останали. След като заместим символите с 0 и 1 получаваме:   110100100  и така след преобразуване в 8-мична бр. система получаваме 644.

# 2. Задаване чрез букви: има следния синтаксис: [Кой] [Действие] [Какво]

# Кой: user, group, others, all
# Действие: + добавя право, - премахва право, = сменя изцяло правата за достъп с тези, който стоят от дясната страна на равенството
# Какво: read, write, execute

